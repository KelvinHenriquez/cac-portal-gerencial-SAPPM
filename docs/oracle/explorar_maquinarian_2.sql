PROMPT ===== 8. Cómo se guardan las horas y si la semana se repite dentro de un reporte =====
SELECT 'HORA' AS QUE, HORA AS VALOR, ESTADO, COUNT(*) AS FILAS
FROM   MAQUINARIAN.MA_CONFIG_HORA_DISP GROUP BY HORA, ESTADO
UNION ALL
SELECT 'SEMANA REPETIDA', ID_AREA_SERVICIO || '/' || ID_TIPO_REPORTE || ' sem ' || NO_SEMANA, NULL, COUNT(*)
FROM   MAQUINARIAN.MA_CONFIG_SEMANA_DISP
GROUP BY ID_EMPRESA, ID_AREA_SERVICIO, ID_TIPO_REPORTE, NO_SEMANA HAVING COUNT(*) > 1
ORDER BY 1, 2;

PROMPT ===== 9. Asignaciones de los reportes que usan grupos =====
SELECT a.ID_AREA_SERVICIO, a.ID_TIPO_REPORTE, a.ORDEN, a.CORRELATIVO, a.DESCRIPCION, a.IND_GRUPO,
       a.IND_NEGRITA, a.CANT, a.CANT_REQ, a.DISP_COMP,
       (SELECT COUNT(*) FROM MAQUINARIAN.MA_DEQUIPOS_REQ_X_FAMILIA d
        WHERE d.ID_EMPRESA = a.ID_EMPRESA AND d.ID_AREA_SERVICIO = a.ID_AREA_SERVICIO
        AND d.ID_TIPO_REPORTE = a.ID_TIPO_REPORTE AND d.CORRELATIVO = a.CORRELATIVO) AS EQUIPOS,
       -- de esos equipos, cuántos están también en una fila de grupo del mismo reporte
       (SELECT COUNT(*) FROM MAQUINARIAN.MA_DEQUIPOS_REQ_X_FAMILIA d
        WHERE d.ID_EMPRESA = a.ID_EMPRESA AND d.ID_AREA_SERVICIO = a.ID_AREA_SERVICIO
        AND d.ID_TIPO_REPORTE = a.ID_TIPO_REPORTE AND d.CORRELATIVO = a.CORRELATIVO
        AND EXISTS (SELECT 1 FROM MAQUINARIAN.MA_DEQUIPOS_REQ_X_FAMILIA g
                    JOIN MAQUINARIAN.MA_EQUIPOS_REQ_X_FAMILIA ga
                      ON ga.ID_EMPRESA = g.ID_EMPRESA AND ga.ID_AREA_SERVICIO = g.ID_AREA_SERVICIO
                     AND ga.ID_TIPO_REPORTE = g.ID_TIPO_REPORTE AND ga.CORRELATIVO = g.CORRELATIVO
                    WHERE g.ID_EMPRESA = d.ID_EMPRESA AND g.ID_AREA_SERVICIO = d.ID_AREA_SERVICIO
                    AND g.ID_TIPO_REPORTE = d.ID_TIPO_REPORTE AND g.IDENTIFICADOR = d.IDENTIFICADOR
                    AND g.CORRELATIVO <> d.CORRELATIVO AND UPPER(ga.IND_GRUPO) IN ('S', 'SI'))) AS EN_UN_GRUPO
FROM   MAQUINARIAN.MA_EQUIPOS_REQ_X_FAMILIA a
WHERE  (a.ID_EMPRESA, a.ID_AREA_SERVICIO, a.ID_TIPO_REPORTE) IN
       (SELECT ID_EMPRESA, ID_AREA_SERVICIO, ID_TIPO_REPORTE FROM MAQUINARIAN.MA_EQUIPOS_REQ_X_FAMILIA
        WHERE UPPER(IND_GRUPO) IN ('S', 'SI'))
ORDER BY a.ID_AREA_SERVICIO, a.ID_TIPO_REPORTE, a.ORDEN;

PROMPT ===== 10. Maestro de equipos: estados, fichas vacías o repetidas =====
SELECT 'ESTADO' AS QUE, NVL(e.ESTADO, '(vacío)') AS VALOR, COUNT(*) AS EQUIPOS
FROM   MAQUINARIAN.MA_MAESTRO_EQUIPOS e GROUP BY e.ESTADO
UNION ALL
SELECT 'ID_ESTADO_EQUIPO', e.ID_ESTADO_EQUIPO || ' ' || s.DESCRIPCION, COUNT(*)
FROM   MAQUINARIAN.MA_MAESTRO_EQUIPOS e
LEFT JOIN MAQUINARIAN.MA_ESTADO_EQUIPO s ON s.ID_EMPRESA = e.ID_EMPRESA AND s.ID_ESTADO_EQUIPO = e.ID_ESTADO_EQUIPO
GROUP BY e.ID_ESTADO_EQUIPO, s.DESCRIPCION
UNION ALL
SELECT 'FICHA VACÍA', NULL, COUNT(*) FROM MAQUINARIAN.MA_MAESTRO_EQUIPOS WHERE FICHA IS NULL
UNION ALL
SELECT 'FICHA REPETIDA', FICHA, COUNT(*) FROM MAQUINARIAN.MA_MAESTRO_EQUIPOS
WHERE FICHA IS NOT NULL GROUP BY FICHA HAVING COUNT(*) > 1
UNION ALL
SELECT 'IND_FICHA_OLD_VALID', NVL(IND_FICHA_OLD_VALID, '(vacío)'), COUNT(*) FROM MAQUINARIAN.MA_MAESTRO_EQUIPOS GROUP BY IND_FICHA_OLD_VALID
ORDER BY 1, 2;

PROMPT ===== 11. Reportes de avance y su calendario =====
SELECT e.ID_EMPRESA, e.CORRELATIVO, e.ID_PERIODO, e.ID_AREA, e.ID_TIPO_OT, e.TIPO_REPORTE, e.FECHA_TRABAJAR,
       e.CONCEPTO, e.REF_PLANIFICADA, e.ID_TIPO_SEMANA, e.EJEC_PROCESO,
       s.DESCRIPCION AS CALENDARIO, s.FECHA_INICIO, s.FECHA_FIN, s.ESTADO
FROM   MAQUINARIAN.MA_ENC_CONFIG_AVANCE e
LEFT JOIN MAQUINARIAN.MA_ENC_SEMANA_OT s
       ON s.ID_EMPRESA = e.ID_EMPRESA AND s.ID_PERIODO = e.ID_PERIODO
      AND s.ID_AREA_SERVICIO = e.ID_AREA AND s.CORRELATIVO = e.ID_TIPO_SEMANA
ORDER BY e.ID_PERIODO DESC, e.CORRELATIVO;

PROMPT ===== 12. OT asignadas a familia: marcas y estados de actividad (último período) =====
SELECT 'SELECCIONADO' AS QUE, NVL(o.SELECCIONADO, '(vacío)') AS VALOR, COUNT(*) AS FILAS,
       COUNT(DISTINCT o.NO_ORDEN_TRABAJO) AS OTS
FROM   MAQUINARIAN.MA_OT_CONFIG_AVANCE o
WHERE  o.ID_PERIODO = (SELECT MAX(ID_PERIODO) FROM MAQUINARIAN.MA_ENC_CONFIG_AVANCE)
GROUP BY o.SELECCIONADO
UNION ALL
SELECT 'ID_ESTADO_ACT', TO_CHAR(o.ID_ESTADO_ACT), COUNT(*), COUNT(DISTINCT o.NO_ORDEN_TRABAJO)
FROM   MAQUINARIAN.MA_OT_CONFIG_AVANCE o
WHERE  o.ID_PERIODO = (SELECT MAX(ID_PERIODO) FROM MAQUINARIAN.MA_ENC_CONFIG_AVANCE)
GROUP BY o.ID_ESTADO_ACT
ORDER BY 1, 2;
SELECT * FROM MAQUINARIAN.MA_ESTADO_ACTIVIDAD;

